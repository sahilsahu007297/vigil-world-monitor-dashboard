import { chromium } from '@playwright/test';
const browser = await chromium.launch({channel:'msedge', headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror', e=>console.log('PAGEERROR',e.message));
page.on('console', m=>{if(m.type()==='error') console.log('CONSOLE',m.text().slice(0,300))});
await page.goto(process.env.CHECK_URL || 'https://vigil-world-monitor-dashboard.vercel.app');
const launch=page.getByRole('button',{name:'Launch Dashboard',exact:true});
if(await launch.isVisible()) await launch.click();
await page.waitForTimeout(20000);
console.log(await page.evaluate(async()=>{const m=window._globeMap;return {layers:m?.getStyle()?.layers?.map(l=>l.id),markers:(await m?.getSource('markers')?.getData())?.features?.length,satellites:(await m?.getSource('satellite-points')?.getData())?.features?.length,center:m?.getCenter(),text:document.body.innerText.slice(0,2800)}}));
await page.getByRole('button',{name:'EXPLORE PUBLIC CAMERAS'}).click();
await page.getByRole('button',{name:'Show cameras on map',exact:true}).click();
await page.waitForTimeout(3000);
const point = await page.evaluate(()=>{const m=window._globeMap;const f=m.queryRenderedFeatures({layers:['markers-layer']}).find(f=>f.properties.cameraId);if(!f)return null;const p=m.project(f.geometry.coordinates);const b=m.getCanvas().getBoundingClientRect();return {x:b.x+p.x,y:b.y+p.y}});
console.log('Visible camera marker',point);
if(!point) throw new Error('No camera marker rendered after focus');
await page.mouse.click(point.x,point.y);
await page.getByRole('dialog',{name:'Public camera viewer'}).waitFor();
console.log('Camera marker opens feed viewer');
await page.screenshot({path:'test-results/live-map.png'});
await browser.close();
